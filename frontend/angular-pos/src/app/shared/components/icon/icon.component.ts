export function resolveIconName(nameOrEmoji?: string): string {
  if (!nameOrEmoji) return 'dashboard';
  const trimmed = nameOrEmoji.trim();
  if (ICON_DEFINITIONS[trimmed]) return trimmed;
  if (EMOJI_TO_ICON_MAP[trimmed]) return EMOJI_TO_ICON_MAP[trimmed];
  const lower = trimmed.toLowerCase();
  if (ICON_DEFINITIONS[lower]) return lower;
  return 'dashboard';
}

export function getIconSvg(nameOrEmoji: string, options?: { size?: number | string; strokeWidth?: number; className?: string }): string {
  const iconName = resolveIconName(nameOrEmoji);
  const path = ICON_DEFINITIONS[iconName] || ICON_DEFINITIONS['dashboard'];
  const size = options?.size ?? 20;
  const sw = options?.strokeWidth ?? 2;
  const cls = options?.className ? `pos-icon ${options.className}` : 'pos-icon';

  return `<svg class="${cls}" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="${sw}" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${path}</svg>`;
}

@Component({
  selector: 'app-icon',
  standalone: true,
  imports: [CommonModule],
  template: `
    <svg
      class="app-icon"
      [class]="extraClass()"
      [attr.width]="computedSize()"
      [attr.height]="computedSize()"
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      [attr.stroke-width]="strokeWidth"
      stroke-linecap="round"
      stroke-linejoin="round"
      [style.color]="color || null"
      aria-hidden="true"
      [innerHTML]="svgContent()">
    </svg>
  `,
  styles: [`
    :host {
      display: inline-flex;
      align-items: center;
      justify-content: center;
      line-height: 1;
      vertical-align: middle;
      flex-shrink: 0;
    }
    .app-icon {
      display: block;
      color: var(--icon-color, #243B64);
      transition: color 200ms ease, transform 200ms ease;
    }
  `]
})
export class AppIconComponent {
  @Input() name = 'dashboard';
  @Input() size: number | string = 20;
  @Input() strokeWidth = 2;
  @Input() color?: string;
  @Input('class') set classList(val: string) {
    this._class = val;
  }
  private _class = '';

  extraClass = computed(() => this._class);

  computedSize = computed(() => {
    if (typeof this.size === 'number') return `${this.size}px`;
    if (!this.size) return '20px';
    return isNaN(Number(this.size)) ? this.size : `${this.size}px`;
  });

  svgContent = computed(() => {
    const iconName = resolveIconName(this.name);
    return ICON_DEFINITIONS[iconName] || ICON_DEFINITIONS['dashboard'];
  });
}
